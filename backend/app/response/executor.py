import os
import datetime as dt
import httpx
import json

# In a real app, this points to your Shuffle SOAR webhook. 
# Leave empty to skip.
SHUFFLE_WEBHOOK_URL = ""

# A global "database" for this demo. 
# (In Step 22, we will connect this to your actual SQLAlchemy DB)
_MOCK_ACTIONS_DB = {}
_action_counter = 1

def plan_actions(case_id: int, decision: dict, ev: dict) -> list[dict]:
    """Creates Action records based on the policy decision."""
    global _action_counter
    
    created_actions = []
    for action_type in decision.get("actions", []):
        # Determine state
        state = "pending_approval" if decision.get("needs_approval") else "simulated"
        
        # Build payload based on action type
        payload = {"domain": ev.get("domain", {}).get("registered_domain", "unknown.com")}
        if action_type == "ticket":
            payload["summary"] = ev.get("summary", "Suspicious activity")
            
        action_id = _action_counter
        _action_counter += 1
        
        act = {
            "id": action_id,
            "case_id": case_id,
            "type": action_type,
            "state": state,
            "payload": payload,
            "created_at": dt.datetime.utcnow().isoformat()
        }
        _MOCK_ACTIONS_DB[action_id] = act
        created_actions.append(act)
        
        print(f"[Action Planned] ID={action_id} Type={action_type} State={state}")
        
    return created_actions

def execute_action(action_id: int, approver: str = "system") -> dict:
    """Simulates the execution of an action."""
    act = _MOCK_ACTIONS_DB.get(action_id)
    if not act:
        return {"error": "Action not found"}
        
    if act["state"] not in ["pending_approval", "simulated"]:
        return {"error": f"Cannot execute action in state: {act['state']}"}

    # --- SIMULATE ACTIONS ---
    if act["type"] == "block_url":
        domain = act["payload"].get("domain")
        # Write to a local blocklist file
        with open("blocklist.txt", "a") as f:
            f.write(f"{domain}\n")
        print(f"  -> [SIMULATED] Blocked {domain} (appended to blocklist.txt)")
        
    elif act["type"] == "report_registrar":
        # Create an artifact
        os.makedirs("artifacts", exist_ok=True)
        filename = f"artifacts/report_{act['case_id']}.txt"
        with open(filename, "w") as f:
            f.write(f"Phishing Report\nTarget: {act['payload'].get('domain')}\nGenerated by PS25 Agent.")
        print(f"  -> [SIMULATED] Generated report at {filename}")
        
    elif act["type"] == "quarantine_email":
        print(f"  -> [SIMULATED] Quarantined email for case {act['case_id']}")
        
    elif act["type"] == "ticket":
        print(f"  -> [SIMULATED] Created SOC Ticket: {act['payload'].get('summary')}")

    # Update state
    act["state"] = "executed"
    act["executed_by"] = approver
    act["executed_at"] = dt.datetime.utcnow().isoformat()
    
    # Trigger SOAR Webhook (if configured)
    if SHUFFLE_WEBHOOK_URL:
        try:
            httpx.post(SHUFFLE_WEBHOOK_URL, json=act, timeout=5)
            print("  -> [SOAR] Webhook triggered successfully.")
        except Exception as e:
            print(f"  -> [SOAR] Webhook failed: {e}")
            
    return act

def rollback_action(action_id: int, who: str) -> dict:
    """Simulates undoing an executed action."""
    act = _MOCK_ACTIONS_DB.get(action_id)
    if not act or act["state"] != "executed":
        return {"error": "Cannot rollback"}

    if act["type"] == "block_url":
        domain = act["payload"].get("domain")
        # Remove from blocklist
        if os.path.exists("blocklist.txt"):
            with open("blocklist.txt", "r") as f:
                lines = f.readlines()
            with open("blocklist.txt", "w") as f:
                for line in lines:
                    if line.strip() != domain:
                        f.write(line)
        print(f"  -> [SIMULATED] Rolled back block for {domain}")
        
    act["state"] = "rolled_back"
    act["rolled_back_by"] = who
    return act

def get_all_actions() -> list[dict]:
    return list(_MOCK_ACTIONS_DB.values())